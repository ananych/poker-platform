export type Lang = "zh" | "en";
const DICTS: Record<Lang, Record<MsgKey, string>> = { zh, en };
const STORAGE_KEY = "lang";

export type TFn = (key: MsgKey, vars?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
  let s: string = DICTS[lang][key] ?? zh[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Current language for non-React code (api error text, etc.). */
let currentLang: Lang = "zh";
export function getLang(): Lang { return currentLang; }

function detect(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "zh" || saved === "en") return saved;
  } catch { /* storage blocked */ }
  const nav = typeof navigator !== "undefined" ? navigator.language || "" : "";
  return nav.toLowerCase().startsWith("zh") ? "zh" : "en";
}

interface Ctx { lang: Lang; setLang: (l: Lang) => void; t: TFn }
const I18nCtx = createContext<Ctx>({
  lang: "zh", setLang: () => {}, t: (k, v) => translate("zh", k, v),
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("zh");
  useEffect(() => { setLangState(detect()); }, []);
  useEffect(() => {
    currentLang = lang;
    document.documentElement.lang = lang === "zh" ? "zh-Hant" : "en";
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try { localStorage.setItem(STORAGE_KEY, l); } catch { /* ignore */ }
  }, []);
  const value = useMemo<Ctx>(() => {
    currentLang = lang;
    return { lang, setLang, t: (k, v) => translate(lang, k, v) };
  }, [lang, setLang]);
  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export function useT() { return useContext(I18nCtx); }

export function LangToggle({ className = "" }: { className?: string }) {
  const { lang, setLang } = useT();
  return (
    <button type="button" onClick={() => setLang(lang === "zh" ? "en" : "zh")}
            className={`h-11 min-w-11 rounded-lg px-2 text-xs text-neutral-300 ${className}`}
            aria-label={lang === "zh" ? "Switch to English" : "切換成中文"}>
      {lang === "zh" ? "EN" : "中"}
    </button>
  );
}
